package app

import (
	"context"
	"errors"
	"time"

	"github.com/google/uuid"

	"github.com/opsolete/opsolete/internal/storage"
)

// Service tokens: automation (the Terraform provider, scripts) acts with admin rights as the token itself, not as a
// person; the audit log names it token:<name>. Admins create and revoke them (Settings → API tokens), or the server's
// CLI registers one (opsolete api-token) to bootstrap: Terraform needs a token before it can create anything.

// ServiceTokenActor is how a service token acts: an admin without a user.
func ServiceTokenActor(name string) Actor { return Actor{Email: "token:" + name, Admin: true} }

// ServiceTokens lists the service tokens. Admins only.
func (a *App) ServiceTokens(ctx context.Context, actor Actor) ([]storage.ServiceToken, error) {
	if !actor.Admin {
		return nil, errAdminsOnly
	}
	return a.Store.ServiceTokens(ctx)
}

// CreateServiceToken creates a service token (expires nil: never) and returns it, shown once. Admins only;
// ValidationError: name (the workspace name rule; taken), expires (not in the future).
func (a *App) CreateServiceToken(ctx context.Context, actor Actor, name string, expires *time.Time) (string, error) {
	if !actor.Admin {
		return "", errAdminsOnly
	}
	if !ValidName(name) {
		return "", invalid("name", NameRule)
	}
	if expires != nil && !expires.After(time.Now()) {
		return "", invalid("expires", "must be in the future")
	}
	_, token, err := a.Store.CreateServiceToken(ctx, name, expires)
	if errors.Is(err, storage.ErrTokenNameTaken) {
		return "", invalid("name", "a service token with this name exists: revoke it first")
	}
	if err != nil {
		return "", err
	}
	a.Log.Info("service token created", "name", name, "user", actor.Email)
	return token, nil
}

// RegisterServiceToken registers token, generated by the caller (a deployment's secret store), as the named service
// token, never expiring, replacing that token's old value. Admins only (the server's CLI); ValidationError: name,
// token (at least 32 characters).
func (a *App) RegisterServiceToken(ctx context.Context, actor Actor, name, token string) error {
	if !actor.Admin {
		return errAdminsOnly
	}
	if !ValidName(name) {
		return invalid("name", NameRule)
	}
	if len(token) < 32 {
		return invalid("token", "at least 32 characters")
	}
	if _, err := a.Store.SetServiceToken(ctx, name, token); err != nil {
		return err
	}
	a.Log.Info("service token registered", "name", name, "user", actor.Email)
	return nil
}

// RevokeServiceToken revokes a service token at once: its next request is refused. Admins only; ErrNotFound.
func (a *App) RevokeServiceToken(ctx context.Context, actor Actor, id uuid.UUID) error {
	if !actor.Admin {
		return errAdminsOnly
	}
	if err := a.Store.DeleteServiceToken(ctx, id); err != nil {
		return err
	}
	a.Log.Info("service token revoked", "id", id, "user", actor.Email)
	return nil
}

// ServiceTokenName is the name of the unexpired service token token; ErrNotFound otherwise.
func (a *App) ServiceTokenName(ctx context.Context, token string) (string, error) {
	name, err := a.Store.ServiceTokenName(ctx, token)
	return name, err
}
